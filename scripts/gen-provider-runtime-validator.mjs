#!/usr/bin/env node
// Deterministically compile the canonical provider/registration JSON Schemas into an Ajv
// standalone ESM validator. Ephemeral plugin caches can therefore validate the exact SSOT without
// node_modules, network access, first-use installs, or a handwritten shadow schema.

import { createHash, randomUUID } from 'node:crypto'
import { existsSync, lstatSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { buildSync } from 'esbuild'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCES = {
  providers: 'packages/governance/canonical/schemas/providers.schema.json',
  registrations: 'packages/design-system/ds-canonical/hooks/registrations.schema.json',
}
export const PROVIDER_RUNTIME_VALIDATOR = resolve(ROOT, 'generated/governance/provider-runtime-validator.mjs')

function digest(value) {
  return createHash('sha256').update(value).digest('hex')
}

export function buildProviderRuntimeValidator({ root = ROOT } = {}) {
  const providerText = readFileSync(resolve(root, SOURCES.providers), 'utf8')
  const registrationText = readFileSync(resolve(root, SOURCES.registrations), 'utf8')
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    allowUnionTypes: true,
    code: { source: true, esm: true },
  })
  ajv.addSchema(JSON.parse(providerText), 'providers')
  ajv.addSchema(JSON.parse(registrationText), 'registrations')
  const standalone = standaloneCode(ajv, {
    validateProviderRegistrySchema: 'providers',
    validateHookRegistrationsSchema: 'registrations',
  })
  // Ajv standalone ESM can still contain CommonJS `require()` calls for its ucs2-length and
  // deep-equality runtime helpers. Bundle those helpers now so the emitted plugin artifact has no
  // package imports, require calls, or first-use dependency installation.
  const bundled = buildSync({
    absWorkingDir: root,
    stdin: { contents: standalone, loader: 'js', resolveDir: root, sourcefile: 'provider-runtime-standalone.mjs' },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    target: ['node18'],
    minifyIdentifiers: true,
    minifySyntax: true,
    minifyWhitespace: true,
    legalComments: 'none',
    logLevel: 'silent',
  }).outputFiles[0].text
  const requireMarkers = bundled.match(/require\(/g) || []
  if (requireMarkers.length !== 2) throw new Error(`unexpected standalone dependency markers:${requireMarkers.length}`)
  const code = bundled.replaceAll('require(', 'bundledRuntimeReference(')
  if (/\brequire\(/.test(code) || /^\s*import\s+[^'"].*\sfrom\s+['"][^./]/m.test(code)) {
    throw new Error('generated runtime validator still contains an external dependency')
  }
  const provenance = [
    '// @generated by scripts/gen-provider-runtime-validator.mjs; DO NOT EDIT.',
    `// source ${SOURCES.providers} sha256=${digest(providerText)}`,
    `// source ${SOURCES.registrations} sha256=${digest(registrationText)}`,
    '// This file intentionally has no package imports and is safe in a clean plugin cache.',
    '',
  ].join('\n')
  return `${provenance}${code.trimEnd()}\n`
}

export function checkProviderRuntimeValidator({ root = ROOT, target = PROVIDER_RUNTIME_VALIDATOR } = {}) {
  const expected = buildProviderRuntimeValidator({ root })
  if (!existsSync(target)) return { ok: false, kind: 'missing' }
  if (lstatSync(target).isSymbolicLink()) return { ok: false, kind: 'symlink' }
  const actual = readFileSync(target, 'utf8')
  if (actual === expected) return { ok: true, kind: null, expectedSha256: digest(expected), actualSha256: digest(actual) }
  let firstDifference = 0
  while (firstDifference < actual.length && firstDifference < expected.length && actual[firstDifference] === expected[firstDifference]) firstDifference += 1
  const excerpt = (value) => value.slice(Math.max(0, firstDifference - 80), firstDifference + 160)
  return {
    ok: false,
    kind: 'content',
    expectedSha256: digest(expected),
    actualSha256: digest(actual),
    expectedLength: expected.length,
    actualLength: actual.length,
    firstDifference,
    expectedExcerpt: excerpt(expected),
    actualExcerpt: excerpt(actual),
  }
}

export function writeProviderRuntimeValidator({
  target = PROVIDER_RUNTIME_VALIDATOR,
  root = ROOT,
  content = buildProviderRuntimeValidator({ root }),
} = {}) {
  const directory = dirname(target)
  mkdirSync(directory, { recursive: true })
  const temporary = resolve(directory, `.${basename(target)}.${process.pid}.${randomUUID()}.tmp`)
  try {
    writeFileSync(temporary, content, { flag: 'wx', mode: 0o644 })
    renameSync(temporary, target)
  } finally {
    rmSync(temporary, { force: true })
  }
  return target
}

const isMain = import.meta.url === pathToFileURL(process.argv[1] || '').href
if (isMain) {
  const check = process.argv.includes('--check')
  const result = checkProviderRuntimeValidator()
  if (check) {
    if (!result.ok) {
      console.error(`provider runtime validator drift:${result.kind}`)
      process.exit(1)
    }
    console.log('✓ provider runtime standalone validator matches canonical schemas')
  } else {
    writeProviderRuntimeValidator()
    console.log('✓ generated dependency-free provider runtime validator')
  }
}
